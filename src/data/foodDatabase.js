export function calculateIngredientNutrition(foodIdOrIngredient, quantity, unit) {
  let targetFoodId = foodIdOrIngredient;
  let targetQty = quantity;

  if (typeof foodIdOrIngredient === 'object' && foodIdOrIngredient !== null) {
    targetFoodId = foodIdOrIngredient.foodId || foodIdOrIngredient.id;
    targetQty = foodIdOrIngredient.quantity;
  }

  const food = foodDatabase.find((f) => f.id === targetFoodId);
  if (!food) {
    return { calories: 0, protein: 0, carbs: 0, fat: 0, fiber: 0 };
  }

  const qty = Number(targetQty) || 0;
  // Factor based on baseAmount
  const factor = food.baseAmount > 0 ? qty / food.baseAmount : qty;

  return {
    calories: Math.round(food.calories * factor),
    protein: Math.round(food.protein * factor * 10) / 10,
    carbs: Math.round(food.carbs * factor * 10) / 10,
    fat: Math.round(food.fat * factor * 10) / 10,
    fiber: Math.round(food.fiber * factor * 10) / 10,
  };
}

/**
 * Calculates total and per-serving nutrition for a recipe from its ingredients
 */
export function calculateRecipeNutrition(ingredients, servings = 1) {
  const numServings = Math.max(1, Number(servings) || 1);

  const total = (ingredients || []).reduce(
    (acc, ing) => {
      const ingNutri = calculateIngredientNutrition(ing.foodId, ing.quantity, ing.unit);
      return {
        calories: acc.calories + ingNutri.calories,
        protein: Math.round((acc.protein + ingNutri.protein) * 10) / 10,
        carbs: Math.round((acc.carbs + ingNutri.carbs) * 10) / 10,
        fat: Math.round((acc.fat + ingNutri.fat) * 10) / 10,
        fiber: Math.round((acc.fiber + ingNutri.fiber) * 10) / 10,
      };
    },
    { calories: 0, protein: 0, carbs: 0, fat: 0, fiber: 0 }
  );

  const perServing = {
    calories: Math.round(total.calories / numServings),
    protein: Math.round((total.protein / numServings) * 10) / 10,
    carbs: Math.round((total.carbs / numServings) * 10) / 10,
    fat: Math.round((total.fat / numServings) * 10) / 10,
    fiber: Math.round((total.fiber / numServings) * 10) / 10,
  };

  return { total, perServing };
}

