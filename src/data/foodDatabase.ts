export function calculateRecipeNutrition(
  ingredients: RecipeIngredient[],
  servings: number = 1
): { total: RecipeNutrition; perServing: RecipeNutrition } {
  let totalCalories = 0;
  let totalProtein = 0;
  let totalCarbs = 0;
  let totalFat = 0;
  let totalFiber = 0;

  for (const ing of ingredients) {
    const food = foodDatabase.find((f) => f.id === ing.foodId);
    if (!food) continue;

    const baseAmount = food.baseAmount || 100;
    const ratio = (Number(ing.quantity) || 0) / baseAmount;

    totalCalories += (food.calories || 0) * ratio;
    totalProtein += (food.protein || 0) * ratio;
    totalCarbs += (food.carbs || 0) * ratio;
    totalFat += (food.fat || 0) * ratio;
    totalFiber += (food.fiber || 0) * ratio;
  }

  const s = Math.max(1, servings);

  return {
    total: {
      calories: Math.round(totalCalories),
      protein: Math.round(totalProtein * 10) / 10,
      carbs: Math.round(totalCarbs * 10) / 10,
      fat: Math.round(totalFat * 10) / 10,
      fiber: Math.round(totalFiber * 10) / 10,
    },
    perServing: {
      calories: Math.round(totalCalories / s),
      protein: Math.round((totalProtein / s) * 10) / 10,
      carbs: Math.round((totalCarbs / s) * 10) / 10,
      fat: Math.round((totalFat / s) * 10) / 10,
      fiber: Math.round((totalFiber / s) * 10) / 10,
    },
  };
}
