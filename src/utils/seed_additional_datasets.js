async function seedAllAdditionalDatasets() {
  console.log('================================================================');
  console.log('IMPORTING 5 ADDITIONAL INDIAN FOOD DATASETS INTO VITALIS');
  console.log('1. Indian Food Nutritional Values Dataset (Kaggle)');
  console.log('2. OpenNosh Gujarati & North Indian Datasets');
  console.log('3. Nourish Indian Food Dataset (ICMR-NIN Validated)');
  console.log('4. Anna-Data Indian Culinary Dataset (Hugging Face)');
  console.log('5. inrfood API Dataset');
  console.log('================================================================\n');

  const candidates = [
    ...kaggleIndianFoods,
    ...openNoshGujaratiFoods,
    ...nourishIndianFoods,
    ...annaDataFoods,
    ...inrFoodApiData,
  ];

  console.log(`Candidate foods across all 5 datasets: ${candidates.length}`);

  // Fetch all existing foods from Supabase
  let allExisting = [];
  let from = 0;
  const pageSize = 1000;
  while (true) {
    const { data: batch, error: fetchErr } = await supabase
      .from('foods')
      .select('name')
      .range(from, from + pageSize - 1);

    if (fetchErr) {
      console.error('❌ Error fetching existing foods:', fetchErr);
      return;
    }
    allExisting = allExisting.concat(batch || []);
    if (!batch || batch.length < pageSize) break;
    from += pageSize;
  }

  const existingNames = new Set((allExisting || []).map(r => r.name.toLowerCase().trim()));
  console.log(`Found ${existingNames.size} existing foods in database.`);

  const toInsert = [];
  const skipped = [];

  for (const food of candidates) {
    const key = food.name.toLowerCase().trim();
    if (existingNames.has(key)) {
      skipped.push(food.name);
    } else {
      toInsert.push({
        name: food.name,
        category: food.category,
        portion_description: food.portion_description,
        base_amount: food.base_amount,
        base_unit: food.base_unit,
        calories: food.calories,
        protein: food.protein,
        carbs: food.carbs,
        fat: food.fat,
        fiber: food.fiber,
        user_id: null,
      });
      existingNames.add(key);
    }
  }

  console.log(`\nReady to insert: ${toInsert.length} new unique Indian foods.`);
  console.log(`Skipped duplicates against existing database: ${skipped.length} foods.`);

  // Write SQL Migration
  const migrationPath = path.join(__dirname, '../../supabase/migrations/20260907000004_seed_additional_indian_datasets.sql');
  let sqlContent = `-- ==============================================================================\n`;
  sqlContent += `-- VITALIS FOOD DATABASE: MULTI-SOURCE INDIAN DATASETS SEED\n`;
  sqlContent += `-- Sources:\n`;
  sqlContent += `-- 1. Indian Food Nutritional Values Dataset (Kaggle)\n`;
  sqlContent += `-- 2. OpenNosh Gujarati & North Indian Datasets\n`;
  sqlContent += `-- 3. Nourish Indian Food Dataset (ICMR-NIN Validated)\n`;
  sqlContent += `-- 4. Anna-Data Indian Culinary Dataset (Hugging Face)\n`;
  sqlContent += `-- 5. inrfood API Data\n`;
  sqlContent += `-- Total new unique foods: ${toInsert.length}\n`;
  sqlContent += `-- User ID: NULL (System Food reference catalog)\n`;
  sqlContent += `-- ==============================================================================\n\n`;
  sqlContent += `INSERT INTO public.foods (name, category, portion_description, base_amount, base_unit, calories, protein, carbs, fat, fiber, user_id) VALUES\n`;

  const valueRows = toInsert.map(f => {
    const nameEsc = f.name.replace(/'/g, "''");
    const catEsc = f.category.replace(/'/g, "''");
    const portionEsc = f.portion_description.replace(/'/g, "''");
    return `  ('${nameEsc}', '${catEsc}', '${portionEsc}', ${f.base_amount}, '${f.base_unit}', ${f.calories}, ${f.protein}, ${f.carbs}, ${f.fat}, ${f.fiber}, NULL)`;
  });

  sqlContent += valueRows.join(',\n') + ';\n';

  fs.writeFileSync(migrationPath, sqlContent, 'utf8');
  console.log(`\n✅ Generated migration SQL file: ${migrationPath}`);
}

seedAllAdditionalDatasets();
