async function seedInternationalFoods() {
  console.log('================================================================');
  console.log('VITALIS: SEEDING GLOBAL FOOD-COMPOSITION DATABASES');
  console.log('1. Canadian Nutrient File (CNF) - Health Canada');
  console.log('2. UK CoFID 2021 - McCance and Widdowson');
  console.log('3. Australian Food Composition Database (AFCD Release 3)');
  console.log('4. AUSNUT 2023 - FSANZ');
  console.log('================================================================\n');

  const candidates = [
    ...cnfFoods,
    ...ukCoFidFoods,
    ...afcdFoods,
    ...ausnutFoods,
  ];

  console.log(`Total candidate international foods: ${candidates.length}`);

  // Fetch all existing foods from Supabase for deduplication
  let allExisting = [];
  let from = 0;
  const pageSize = 1000;
  while (true) {
    const { data: batch, error: fetchErr } = await supabase
      .from('foods')
      .select('name')
      .range(from, from + pageSize - 1);

    if (fetchErr) {
      console.error('❌ Error fetching existing foods:', fetchErr);
      return;
    }
    allExisting = allExisting.concat(batch || []);
    if (!batch || batch.length < pageSize) break;
    from += pageSize;
  }

  const existingNames = new Set((allExisting || []).map(r => r.name.toLowerCase().trim()));
  console.log(`Found ${existingNames.size} existing foods in Vitalis database.`);

  const toInsert = [];
  const skipped = [];

  for (const food of candidates) {
    const key = food.name.toLowerCase().trim();
    if (existingNames.has(key)) {
      skipped.push(food.name);
    } else {
      toInsert.push({
        name: food.name,
        category: food.category,
        portion_description: food.portion_description,
        base_amount: food.base_amount,
        base_unit: food.base_unit,
        calories: food.calories,
        protein: food.protein,
        carbs: food.carbs,
        fat: food.fat,
        fiber: food.fiber,
        user_id: null,
      });
      existingNames.add(key);
    }
  }

  console.log(`\nReady to insert: ${toInsert.length} new unique international foods.`);
  console.log(`Skipped duplicate records: ${skipped.length} foods.`);

  // Write SQL migration
  const migrationPath = path.join(__dirname, '../../supabase/migrations/20260907000006_seed_international_food_catalogs.sql');
  let sqlContent = `-- ==============================================================================\n`;
  sqlContent += `-- VITALIS FOOD DATABASE: GLOBAL FOOD COMPOSITION DATABASES SEED\n`;
  sqlContent += `-- Sources:\n`;
  sqlContent += `-- 1. Canadian Nutrient File (CNF) - Health Canada\n`;
  sqlContent += `-- 2. UK CoFID 2021 (McCance and Widdowson) - UK Public Health England\n`;
  sqlContent += `-- 3. Australian Food Composition Database (AFCD Release 3) - FSANZ\n`;
  sqlContent += `-- 4. AUSNUT 2023 - Food Standards Australia New Zealand\n`;
  sqlContent += `-- Total unique records: ${toInsert.length}\n`;
  sqlContent += `-- User ID: NULL (System Food reference catalog)\n`;
  sqlContent += `-- ==============================================================================\n\n`;
  sqlContent += `INSERT INTO public.foods (name, category, portion_description, base_amount, base_unit, calories, protein, carbs, fat, fiber, user_id) VALUES\n`;

  const valueRows = toInsert.map(f => {
    const nameEsc = f.name.replace(/'/g, "''");
    const catEsc = f.category.replace(/'/g, "''");
    const portionEsc = f.portion_description.replace(/'/g, "''");
    return `  ('${nameEsc}', '${catEsc}', '${portionEsc}', ${f.base_amount}, '${f.base_unit}', ${f.calories}, ${f.protein}, ${f.carbs}, ${f.fat}, ${f.fiber}, NULL)`;
  });

  sqlContent += valueRows.join(',\n') + ';\n';

  fs.writeFileSync(migrationPath, sqlContent, 'utf8');
  console.log(`\n✅ Generated migration SQL file: ${migrationPath}`);
}

seedInternationalFoods();
